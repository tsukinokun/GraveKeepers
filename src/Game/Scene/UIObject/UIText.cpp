#include "UIText.h"
#include <System/UIComponent/ComponentString.h>

//---------------------------------------------------------------------------------
//!	初期化
//---------------------------------------------------------------------------------
bool UIText::Init()
{
    __super::Init();
    //---------------------------------------------------------------------------------
    //	文字列機能コンポーネントの追加
    //---------------------------------------------------------------------------------
    auto text_comp  = AddComponent<ComponentString>();    // 文字列機能コンポーネントを追加
    text_component_ = text_comp;                          // weak_ptrとして保持
    return true;
}

//---------------------------------------------------------------------------------
//!	更新
//---------------------------------------------------------------------------------
void UIText::Update()
{
    __super::Update();
}

//---------------------------------------------------------------------------------
//!	描画
//---------------------------------------------------------------------------------
void UIText::Draw()
{
    __super::Draw();
}

//---------------------------------------------------------------------------------
//!	終了
//---------------------------------------------------------------------------------
void UIText::Exit()
{
    __super::Exit();
}

//!GUI表示
void UIText::GUI()
{
    __super::GUI();
}
